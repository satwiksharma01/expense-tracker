package com.expensetracker.service;

import com.expensetracker.model.Budget;
import com.expensetracker.model.Category;
import com.expensetracker.model.Expense;
import com.expensetracker.model.PaymentMethod;
import com.expensetracker.util.Money;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.DayOfWeek;
import java.time.LocalDate;
import java.time.YearMonth;
import java.util.ArrayList;
import java.util.EnumMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.function.Function;
import java.util.stream.Collectors;

/**
 * Reporting and analytics module: monthly summaries, trends, category breakdowns,
 * month-end projections and plain-language spending insights.
 */
public class ReportService {

    private final ExpenseService expenseService;
    private final BudgetService budgetService;

    public ReportService(ExpenseService expenseService, BudgetService budgetService) {
        this.expenseService = expenseService;
        this.budgetService = budgetService;
    }

    public MonthlySummary monthlySummary(YearMonth month) {
        List<Expense> expenses = expenseService.search(ExpenseFilter.forMonth(month), SortOrder.AMOUNT_DESC);
        BigDecimal total = totalOf(expenses);
        int daysElapsed = daysElapsed(month);
        BigDecimal dailyAverage = daysElapsed == 0 ? BigDecimal.ZERO
                : total.divide(BigDecimal.valueOf(daysElapsed), 2, RoundingMode.HALF_UP);
        BigDecimal scheduled = totalOf(expenses.stream().filter(ReportService::isFromSchedule).toList());
        BigDecimal projected = scheduled.add(projectMonthEnd(month, total.subtract(scheduled)));
        return new MonthlySummary(month, total, expenses.size(), dailyAverage, projected,
                sumBy(expenses, Expense::category, Category.class),
                sumBy(expenses, Expense::paymentMethod, PaymentMethod.class),
                expenses.isEmpty() ? null : expenses.get(0));
    }

    /**
     * Linear projection: if the month is in progress, scales the amount spent so far up to the
     * full length of the month. Past months return their actual total; future months zero.
     * {@link #monthlySummary} only applies this to day-to-day spending: payments generated by a
     * recurring schedule (rent, subscriptions) happen once a month and are added unscaled.
     */
    public BigDecimal projectMonthEnd(YearMonth month, BigDecimal spentSoFar) {
        int elapsed = daysElapsed(month);
        if (elapsed == 0 || elapsed == month.lengthOfMonth()) {
            return spentSoFar;
        }
        return spentSoFar.multiply(BigDecimal.valueOf(month.lengthOfMonth()))
                .divide(BigDecimal.valueOf(elapsed), 2, RoundingMode.HALF_UP);
    }

    /** Totals for the {@code months} months ending with {@code endMonth}, oldest first, including empty months. */
    public Map<YearMonth, BigDecimal> monthlyTrend(YearMonth endMonth, int months) {
        YearMonth start = endMonth.minusMonths(Math.max(1, months) - 1L);
        Map<YearMonth, BigDecimal> trend = new LinkedHashMap<>();
        for (YearMonth m = start; !m.isAfter(endMonth); m = m.plusMonths(1)) {
            trend.put(m, BigDecimal.ZERO);
        }
        ExpenseFilter range = ExpenseFilter.all().between(start.atDay(1), endMonth.atEndOfMonth());
        for (Expense e : expenseService.search(range, SortOrder.DATE_ASC)) {
            trend.merge(e.month(), e.amount(), BigDecimal::add);
        }
        return trend;
    }

    public Map<Category, BigDecimal> categoryBreakdown(ExpenseFilter filter) {
        return sumBy(expenseService.search(filter, SortOrder.DATE_ASC), Expense::category, Category.class);
    }

    public List<Expense> topExpenses(ExpenseFilter filter, int limit) {
        return expenseService.search(filter, SortOrder.AMOUNT_DESC).stream().limit(limit).toList();
    }

    /**
     * Short observations about a month's spending that a user may not notice from raw numbers:
     * change versus last month, the dominant category, the category that grew the most,
     * weekend spending share, and whether the current pace will break the overall budget.
     */
    public List<String> insights(YearMonth month) {
        MonthlySummary current = monthlySummary(month);
        List<String> insights = new ArrayList<>();
        if (current.isEmpty()) {
            insights.add("No expenses recorded for " + month + " yet.");
            return insights;
        }
        MonthlySummary previous = monthlySummary(month.minusMonths(1));

        percentChange(previous.total(), current.total()).ifPresent(change -> insights.add(
                "Spending is " + (change.signum() >= 0 ? "up " : "down ") + change.abs() + "% compared with "
                        + previous.month() + " (" + Money.format(previous.total()) + ")."));

        Map.Entry<Category, BigDecimal> top = current.byCategory().entrySet().iterator().next();
        insights.add(top.getKey().label() + " is your biggest category at "
                + Money.percent(top.getValue(), current.total()) + "% of spending.");

        biggestIncrease(previous.byCategory(), current.byCategory()).ifPresent(entry -> insights.add(
                entry.getKey().label() + " grew the most: +" + Money.format(entry.getValue()) + " vs last month."));

        BigDecimal weekend = expenseService.search(ExpenseFilter.forMonth(month), SortOrder.DATE_ASC).stream()
                .filter(e -> isWeekend(e.date()))
                .map(Expense::amount)
                .reduce(BigDecimal.ZERO, BigDecimal::add);
        insights.add("Weekend spending: " + Money.percent(weekend, current.total()) + "% of the month's total.");

        budgetService.list().stream().filter(Budget::isOverall).findFirst().ifPresent(overall -> {
            BigDecimal gap = current.projectedTotal().subtract(overall.monthlyLimit());
            if (gap.signum() > 0) {
                insights.add("At this pace you will overshoot your overall budget by about " + Money.format(gap) + ".");
            } else {
                insights.add("At this pace you will stay within your overall budget ("
                        + Money.format(gap.negate()) + " to spare).");
            }
        });
        return insights;
    }

    /** Percentage change from previous to current; empty when there is no previous spending to compare. */
    public static Optional<BigDecimal> percentChange(BigDecimal previous, BigDecimal current) {
        if (previous.signum() == 0) {
            return Optional.empty();
        }
        return Optional.of(current.subtract(previous).multiply(BigDecimal.valueOf(100))
                .divide(previous, 1, RoundingMode.HALF_UP));
    }

    private static Optional<Map.Entry<Category, BigDecimal>> biggestIncrease(Map<Category, BigDecimal> before,
                                                                            Map<Category, BigDecimal> after) {
        return after.entrySet().stream()
                .map(e -> Map.entry(e.getKey(), e.getValue().subtract(before.getOrDefault(e.getKey(), BigDecimal.ZERO))))
                .filter(e -> e.getValue().signum() > 0)
                .max(Map.Entry.comparingByValue());
    }

    private int daysElapsed(YearMonth month) {
        LocalDate today = expenseService.today();
        YearMonth current = YearMonth.from(today);
        if (month.isAfter(current)) {
            return 0;
        }
        return month.equals(current) ? today.getDayOfMonth() : month.lengthOfMonth();
    }

    private static boolean isFromSchedule(Expense e) {
        return e.description().endsWith(RecurringExpenseService.GENERATED_SUFFIX);
    }

    private static boolean isWeekend(LocalDate date) {
        return date.getDayOfWeek() == DayOfWeek.SATURDAY || date.getDayOfWeek() == DayOfWeek.SUNDAY;
    }

    private static BigDecimal totalOf(List<Expense> expenses) {
        return expenses.stream().map(Expense::amount).reduce(BigDecimal.ZERO, BigDecimal::add);
    }

    /** Groups amounts by an enum key and returns the totals sorted from largest to smallest. */
    private static <E extends Enum<E>> Map<E, BigDecimal> sumBy(List<Expense> expenses,
                                                                Function<Expense, E> key, Class<E> type) {
        Map<E, BigDecimal> totals = expenses.stream().collect(Collectors.groupingBy(key,
                () -> new EnumMap<>(type),
                Collectors.reducing(BigDecimal.ZERO, Expense::amount, BigDecimal::add)));
        return totals.entrySet().stream()
                .sorted(Map.Entry.<E, BigDecimal>comparingByValue().reversed())
                .collect(Collectors.toMap(Map.Entry::getKey, Map.Entry::getValue, (a, b) -> a, LinkedHashMap::new));
    }
}
